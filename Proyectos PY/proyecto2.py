def FullAdder(a, b, carry_in):
    # Suma parcial (a + b)
    sum_temp, carry_temp1 = HalfAdder(a, b)

    # Suma final (sum_temp + carry_in)
    sum_bit, carry_temp2 = HalfAdder(sum_temp, carry_in)

    # Acarreo final (carry_temp1 OR carry_temp2)
    carry_out = Or(carry_temp1, carry_temp2)

    return sum_bit, carry_out

def Add16(a, b):
    result = []
    carry = 0

    # Suma bit por bit (de derecha a izquierda)
    for i in range(15, -1, -1):
        sum_bit, carry = FullAdder(a[i], b[i], carry)
        result.insert(0, sum_bit)  # Insertar al inicio para mantener el orden

    return result

def Inc16(a):
    # Crear un número de 16 bits con valor 1
    one = [0] * 15 + [1]

    # Sumar 1 al número de entrada
    return Add16(a, one)

def ALU(x, y, zx, nx, zy, ny, f, no):
    # Control de la entrada x
    print("\n=== ALU ===")
    if zx == 1:  # Zero x
        x = [0] * 16
        print("(all zero X):", x)
    if nx == 1:  # Negate x
        x = [Not(bit) for bit in x]
        print("(negate x):", x)
    # Control de la entrada y

    if zy == 1:  # Zero y
        y = [0] * 16
        print("(all zero Y):", y)
    if ny == 1:  # Negate y
        y = [Not(bit) for bit in y]
        print("(negate y):", y)

    # Operación
    if f == 1:  # Add operation
        out = Add16(x, y)
        print(f"After ADD (x + y): {out}")
    if f == 0:  # AND operation
        out = [And(x[i], y[i]) for i in range(16)]
        print(f"After AND (x & y): {out}")

    # Negación final
    if no == 1:
        out = [Not(bit) for bit in out]

    # Flags
    zr = 1 if all(bit == 0 for bit in out) else 0
    ng = out[0]  # MSB indicates negative in two's complement

    return out, zr, ng

