def Not (a):
  if (a == 1):
    return 0
  else:
    return 1

def And (a,b):
  if(a == 1 and b == 1):
    return 1
  else:
    return 0

def Or (a,b):
  if(a == 1 or b == 1):
    return 1
  else:
    return 0
def Xor (a,b):
  nota = Not(a)
  notb = Not(b)
  aAndNotb = And(a,notb)
  notaAndb = And(nota,b)
  return Or(aAndNotb,notaAndb)

def HalfAdder(a, b):
    # Suma: XOR de a y b
    sum_bit = Xor(a, b)

    # Acarreo: AND de a y b
    carry_bit = And(a, b)

    return sum_bit, carry_bit

